/**
 * Bundle budget -- `npm run check:bundle` (after `npm run build`).
 *
 * For every page, adds up the JavaScript a browser downloads on first load
 * (Next's shared runtime + the page's own layout/page chunks), gzipped the way
 * it goes over the wire, and fails if any page is over BUDGET_KB. Catches the
 * classic slow-app regression: one import (a chart or QR library, a date
 * library, a whole icon set) quietly landing on every page.
 *
 * Reads Next's own build manifests, so nothing about routes is hard-coded.
 * `--write` also saves the table to docs/performance/bundle-budget.md.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";
import { gzipSync } from "node:zlib";
import vm from "node:vm";

const BUDGET_KB = 300;
const NEXT = ".next";

const build = JSON.parse(readFileSync(join(NEXT, "build-manifest.json"), "utf8"));
const shared = [...build.rootMainFiles, ...build.polyfillFiles];

const gz = new Map();
function gzipKb(file) {
  if (!gz.has(file)) gz.set(file, gzipSync(readFileSync(join(NEXT, file))).length / 1024);
  return gz.get(file);
}

function manifests(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...manifests(p));
    else if (name === "page_client-reference-manifest.js") out.push(p);
  }
  return out;
}

const rows = [];
for (const file of manifests(join(NEXT, "server", "app"))) {
  const ctx = { globalThis: {} };
  ctx.globalThis = ctx;
  vm.runInNewContext(readFileSync(file, "utf8"), ctx);
  for (const [route, m] of Object.entries(ctx.__RSC_MANIFEST ?? {})) {
    const chunks = new Set(shared);
    for (const list of Object.values(m.entryJSFiles ?? {})) for (const c of list) chunks.add(c.replace(/^\//, "").replace(/^_next\//, ""));
    const kb = [...chunks].reduce((sum, c) => sum + gzipKb(c), 0);
    const page = "/" + relative(join(NEXT, "server", "app"), file).replace(/\\/g, "/").replace(/\/?page_client-reference-manifest\.js$/, "");
    rows.push({ route: page.replace(/\/\([^)]+\)/g, "") || "/", kb, over: kb > BUDGET_KB });
    void route;
  }
}
rows.sort((a, b) => b.kb - a.kb);

const table = [
  `# Bundle budget`,
  ``,
  `Generated by \`npm run check:bundle\` on ${new Date().toISOString().slice(0, 10)} from the production build.`,
  `First-load JavaScript per page, gzipped (shared runtime + the page's own chunks). Budget: ${BUDGET_KB} KB.`,
  ``,
  `**Result: ${rows.some((r) => r.over) ? `${rows.filter((r) => r.over).length} page(s) over budget` : `all ${rows.length} pages within budget`}.** Shared by every page: ${shared.reduce((s, c) => s + gzipKb(c), 0).toFixed(0)} KB.`,
  ``,
  `| Page | First-load JS (KB, gzip) | Verdict |`,
  `| --- | ---: | --- |`,
  ...rows.map((r) => `| ${r.route} | ${r.kb.toFixed(0)} | ${r.over ? "❌ over budget" : "✅"} |`),
  ``,
].join("\n");

console.log(table);
if (process.argv.includes("--write")) {
  mkdirSync("docs/performance", { recursive: true });
  writeFileSync("docs/performance/bundle-budget.md", table);
  console.log("Saved docs/performance/bundle-budget.md");
}
process.exitCode = rows.some((r) => r.over) ? 1 : 0;
